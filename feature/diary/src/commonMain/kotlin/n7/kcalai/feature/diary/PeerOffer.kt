package n7.kcalai.feature.diary

import n7.kcalai.database.PeerOfferEntity

/**
 * Предложение соседа словами Яйца.
 *
 * Функцией, а не в разметке — как [outboxOffer]: что сказано, проверяется тестом,
 * а не глазами.
 *
 * «Передаёт», а не «ты съел»: род по имени не угадывается, а приложение говорит
 * о человеке в роде только там, где пол известен. Имя к тому же пришло с чужого
 * телефона и ничем не подтверждено — пересказ здесь честнее утверждения.
 */
fun peerOffer(fromName: String, food: String, grams: Int): String =
    "$fromName передаёт: $food, $grams г. Записать?"

/**
 * Предложение держит слово: пришло после последней записи и ждёт ответа.
 *
 * Пока так, подсказки и итоги молчат — персонажи говорят по одному. Правило то же,
 * что у вопросов персонажей (см. `awaitsAnswer`), и причина та же: человек записал
 * что-то, не ответив, — предложение остаётся с живыми кнопками, но слово уже
 * не держит, ждать ответа вечно незачем.
 *
 * @param lastEntryAt когда сделана последняя запись; `null` — записей нет
 */
fun awaitsOffer(offers: List<PeerOfferEntity>, lastEntryAt: Long?): Boolean =
    offers.any { it.choice == null && it.createdAt >= (lastEntryAt ?: Long.MIN_VALUE) }
