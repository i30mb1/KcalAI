package n7.kcalai.feature.scanner

import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.util.Log
import androidx.test.platform.app.InstrumentationRegistry
import kotlin.math.abs
import kotlinx.coroutines.runBlocking
import n7.kcalai.ocr.LabelOcr
import n7.kcalai.repositories.LabelParser
import n7.kcalai.repositories.LabelReading
import org.junit.Assert.fail
import org.junit.Test

/**
 * Съёмка этикетки целиком, от снимка до КБЖУ.
 *
 * Единственный тест во всём проекте, которому нужно устройство, и это не прихоть:
 * распознаватель — нативный движок с двумя моделями, подменить его заглушкой
 * значит проверить разбор строк, который и так проверен, и не проверить ровно то,
 * что ломается. Между «модель прочитала таблицу» и «разбор её понял» лежит всё
 * интересное: перепутанные глифы, склеенные ячейки, числа, уехавшие в соседнюю
 * колонку. Увидеть это можно только на настоящем снимке.
 *
 * Проверяются все этикетки сразу, а падение собирается одно на всех. Так сделано
 * нарочно: когда правишь распознавание или разбор, надо видеть, что стало со всеми
 * снимками, а не с первым по алфавиту. Тест, падающий на первом же несовпадении,
 * заставляет чинить вслепую.
 *
 * Всё распознанное уходит в лог под тегом `LabelReadingTest`. Когда тест падает,
 * смотреть надо туда: причина чаще в том, что модель прочитала не то, чем в том,
 * что разбор ошибся.
 */
class LabelReadingTest {

    /**
     * Снимок и то, что на нём напечатано.
     *
     * Ожидания сверены глазами по фотографии, а не выводом распознавателя, —
     * иначе тест зафиксировал бы сегодняшнюю ошибку в качестве нормы.
     *
     * @param protG белки, жиры, углеводы в граммах на 100 г или 100 мл —
     *        так, как это стоит на пачке
     */
    private class Label(
        val asset: String,
        val what: String,
        val kcal: Int,
        val protG: Double,
        val fatG: Double,
        val carbG: Double,
        /**
         * Снимок обязан прочитаться целиком.
         *
         * Снят с тех, где распознавание пока не вытягивает, и это честнее, чем
         * ослаблять ожидания до текущего результата: главное требование — [«не
         * врать молча»][КБЖУ_читается_с_фотографий_этикеток] — проверяется на всех
         * трёх, а полное чтение только на тех, где оно достижимо.
         */
        val mustRead: Boolean = true,
    )

    /**
     * Три этикетки, и каждая ломает разбор по-своему.
     *
     * Кукуруза — таблица с колонками: единицы энергии стоят в подписи слева
     * («Калорийность, ккал /»), а числа справа и в две строки, «80/» и «340».
     * Ни одно число не стоит рядом со своей единицей.
     *
     * Напиток — тот самый случай, ради которого подписи вообще различаются
     * с их отсутствием: на этикетке только углеводы и энергия, белков и жиров
     * нет вовсе. Правильный ответ для них — ноль, а не «не прочитали». Вдобавок
     * единица стоит перед числом, а не после: «ккал/100 мл ... 25,0».
     *
     * Майонез — вообще не таблица, а сплошной текст: «жиры - 67 г, белки - 0,4 г,
     * углеводы - 2,1 г» одной строкой. Три подписи в одной строке, и каждой
     * полагается своё число — то, на чём разбор, умеющий видеть одну подпись
     * на строку, ломался целиком. Ниже на той же пачке напечатана таблица
     * на порцию в 25 г со своими «153 ккал» и «16,8 г» — они не должны перебить
     * прочитанное выше.
     *
     * Масло — таблица в три колонки, и нужная в ней не первая: слева «в столовой
     * ложке (10 г)», справа «на 100 г продукта». Разбор берёт ближайшее к подписи
     * число, то есть ложку, и получает девяносто килокалорий вместо восьмисот
     * девяноста девяти — уверенно и ровно в десять раз мимо.
     *
     * Творожок — простая таблица, но энергия в ней напечатана наоборот: крупно
     * килоджоули, а килокалории в скобках под ними, да ещё дробные — «(87,6 ккал)».
     *
     * Полного чтения не требуется от одного майонеза, и упирается это
     * в распознавание, а не в разбор: картинка 740×555 с артефактами сжатия,
     * строка таблицы высотой в десяток пикселей — там рассыпается всё, включая
     * подписи. На живой камере такой кадр не появится.
     */
    private val labels = listOf(
        Label(
            "labels/corn-dixi.webp", "кукуруза «Дикси»",
            kcal = 80, protG = 2.5, fatG = 1.0, carbG = 15.4,
        ),
        Label(
            "labels/corn2.png", "напиток «Ягодный микс»",
            kcal = 25, protG = 0.0, fatG = 0.0, carbG = 6.0,
        ),
        Label(
            "labels/oil.png", "масло подсолнечное",
            kcal = 899, protG = 0.0, fatG = 99.9, carbG = 0.0,
        ),
        Label(
            "labels/curd.png", "творожок «Савушкин продукт»",
            kcal = 88, protG = 2.9, fatG = 2.0, carbG = 14.5,
        ),
        // Кадр с камеры при зуме 2×, а не фото: КБЖУ не таблицей, а в строку
        // абзаца — «белки – 2,5 г, углеводы – 76,0 г. ... 1330 кДж/310 ккал».
        // Строка в двадцать семь высот шириной: без нарезки на куски
        // распознаватель сжимал её вчетверо и отдавал «бе-25-7». Жиров
        // на этикетке нет — ноль по отсутствию подписи, а не прочитанный.
        Label(
            "labels/pastila-belev.jpg", "пастила «Белёвские сладости»",
            kcal = 310, protG = 2.5, fatG = 0.0, carbG = 76.0,
        ),
    )

    // Имя без пробелов, в отличие от юнит-тестов: локальные функции и лямбды внутри
    // становятся вложенными классами, а пробел в имени класса dex до версии 040
    // не принимает — на устройстве это падение сборки, а не стиля.
    @Test
    fun КБЖУ_читается_с_фотографий_этикеток() {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        val problems = mutableListOf<String>()

        LabelOcr(context).use { ocr ->
            for (label in labels) {
                val lines = runBlocking { ocr.read(loadAsset(label.asset)) }

                // null и пустой список — разные беды. Первая означает, что движок
                // не поднялся на этом устройстве вовсе, и тогда проверять нечего.
                if (lines == null) {
                    problems += "${label.what}: OCR не поднялся — движка нет на этом устройстве"
                    continue
                }

                Log.i(TAG, "── ${label.what} (${label.asset}), строк ${lines.size}")
                // С координатами, а не только текстом: разбор связывает подпись
                // со значением по высоте, и когда связь не вышла, из одного текста
                // причину не увидеть.
                lines.forEach {
                    Log.i(
                        TAG,
                        "   y=%4.0f x=%4.0f h=%3.0f  %s".format(
                            it.centerY, it.centerX, it.height, it.text,
                        ),
                    )
                }

                val reading = LabelParser.parseLines(lines)
                Log.i(TAG, "   разбор: ${reading.summary()}")
                Log.i(
                    TAG,
                    "   подписи: ${reading.trace.readLabels}, " +
                        "нулями: ${reading.trace.zeroedLabels}, " +
                        "таблица: ${reading.trace.tableFound}",
                )

                problems += mismatches(label, reading)
            }
        }

        if (problems.isNotEmpty()) {
            fail("\n" + problems.joinToString("\n") + "\n(распознанные строки — в логе по тегу $TAG)")
        }
    }

    /**
     * Главное требование — не соврать молча.
     *
     * Числа сверяются только у разбора, объявившего себя сошедшимся: именно он
     * закрывает съёмку сам и подставляет значения в форму, не спрашивая. Ошибка
     * здесь и есть худшее, что приложение может сделать, — тихо записать в дневник
     * чужие калории. Разбор, признавший, что не сошёлся, ничего не утверждает:
     * форма остаётся открытой, числа с этикетки лежат чипсами, решает человек.
     * Требовать от него правильных значений незачем — он их и не обещал.
     */
    private fun mismatches(label: Label, reading: LabelReading): List<String> = buildList {
        if (!reading.confident) {
            if (label.mustRead) {
                add("${label.what}: разбор не сошёлся, хотя на этикетке есть все четыре значения")
            }
            return@buildList
        }

        val draft = reading.draft
        fun check(what: String, expected: Int, actual: Int?) {
            if (actual == null || abs(actual - expected) > MACRO_TOLERANCE_CG) {
                add("${label.what}: уверенно, но $what ожидалось $expected, вышло $actual")
            }
        }

        // Калориям — допуск в пару единиц. Когда напечатанные килокалории
        // распознались неверно, разбор берёт их из килоджоулей, а обратный
        // пересчёт округляется не туда же, куда округлил производитель.
        val kcal = draft.kcal100
        if (kcal == null || abs(kcal - label.kcal) > KCAL_TOLERANCE) {
            add("${label.what}: уверенно, но ккал ожидалось ${label.kcal}, вышло $kcal")
        }
        check("белки, сотые грамма", label.protG.toCentigrams(), draft.prot100)
        check("жиры, сотые грамма", label.fatG.toCentigrams(), draft.fat100)
        check("углеводы, сотые грамма", label.carbG.toCentigrams(), draft.carb100)
    }

    private fun Double.toCentigrams(): Int = Math.round(this * 100).toInt()

    private fun loadAsset(path: String): Bitmap {
        val assets = InstrumentationRegistry.getInstrumentation().context.assets
        return assets.open(path).use { BitmapFactory.decodeStream(it) }
            ?: error("не удалось прочитать $path")
    }

    private companion object {
        const val TAG = "LabelReadingTest"

        /**
         * Допуски на округление, а не на ошибку.
         *
         * Значение, которое разбор не прочитал, а досчитал по Этуотеру из трёх
         * остальных, округляется не туда же, куда округлил производитель: у масла
         * выходит 99,89 г жира против напечатанных 99,9, у кукурузы 81 ккал против
         * восьмидесяти. Десятая грамма и пара килокалорий — предел этого расхождения;
         * всё, что больше, — уже не округление, а другое число.
         */
        const val KCAL_TOLERANCE = 2
        const val MACRO_TOLERANCE_CG = 10
    }
}
