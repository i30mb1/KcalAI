package n7.kcalai.feature.scanner

/**
 * Где сейчас съёмка.
 *
 * Окно одно — от штрих-кода до карточки нового продукта. Раньше промах скана
 * закрывал сканер, на мгновение показывал дневник и открывал второе окно со
 * своей камерой: экран мигал, камера запускалась заново, а человек терял пачку
 * из кадра. Теперь шаги сменяют друг друга в том же окне, и камера не гаснет.
 */
sealed interface ScanStep {

    /** Камера ищет штрих-код. */
    data object Barcode : ScanStep

    /** Код прочитан, товар ищется в базе и в сети. Окно ждёт ответа открытым. */
    data class Searching(val gtin: String) : ScanStep

    /**
     * Товара нигде нет — его заводят здесь же: камера читает таблицу КБЖУ,
     * чего не прочла, человек вписывает сам.
     *
     * Единственный путь завести продукт — и для промаха штрих-кода, и для
     * развесного, домашнего, вскрытой пачки. Промах скана — исход основной,
     * а не аварийный (российских товаров в Open Food Facts порядка тридцати
     * шести тысяч), и вести к нему через второе окно было незачем.
     *
     * @param gtin код, с промаха которого сюда пришли. `null` — этикетку снимают
     *        напрямую, без кода; камера попробует поймать его сама.
     */
    data class NewProduct(val gtin: String? = null) : ScanStep
}
