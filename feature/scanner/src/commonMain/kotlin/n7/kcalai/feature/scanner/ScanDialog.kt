 *
 * @param onCamera под значками статуса превью: они светлые, затемнение под ними
 *        есть всегда. Без камеры — ручной ввод кода, отказ в доступе — под ними
 *        фон темы, и в светлой теме белые часы на бежевом не видны.
 */
