package n7.kcalai.repositories

import kotlin.math.abs
import n7.kcalai.model.Nutriments

/**
 * Итог проверки введённого руками КБЖУ.
 *
 * Две ступени, а не одна, и различие принципиальное. [error] — это невозможное:
 * такого продукта не существует, и сохранять его нельзя. [warning] — это странное:
 * цифры не сходятся между собой, но напечатаны именно так на упаковке, и спорить
 * с упаковкой приложение не вправе. Человек видит замечание и решает сам.
 */
data class NutrimentCheck(
    val error: String? = null,
    val warning: String? = null,
) {
    val valid: Boolean get() = error == null
}

/**
 * Те же инварианты, что проверяет `tools/builddb/build_seed.py` на сборке справочника.
 *
 * Ручной ввод — вторая дверь в те же данные, и оставлять её без замка бессмысленно:
 * абсурдная цифра, попавшая в `user_food`, портит дневник навсегда, а попавшая
 * в очередь отправки — уезжает к другим людям. Пределы и формула держатся
 * одинаковыми с обеих сторон намеренно: разъехавшись, они дадут продукты,
 * которые проходят на клиенте и отклоняются на сборке.
 */
object NutrimentValidator {

    /** Выше чистого жира не бывает: 900 ккал на 100 г — физический потолок. */
    const val KCAL_MAX = 100 * 9

    /** Сотые грамма в ста граммах. Больше ста грамм в ста граммах не помещается. */
    private const val CENTIGRAMS_MAX = 100 * 100

    /**
     * Ниже этого порога сверка энергобаланса бессмысленна: у зелени и напитков
     * макросы околонулевые, и относительная погрешность там ничего не значит.
     */
    private const val BALANCE_MIN_KCAL = 20

    /**
     * Допуск четверть — клетчатка, многоатомные спирты и округление на этикетке.
     *
     * Публичный, потому что тем же допуском разбор этикетки выбирает, какое
     * из распознанных чисел белок, а какое жир: расходись эти два числа —
     * разбор предлагал бы наборы, которые форма тут же помечает подозрительными.
     */
    const val BALANCE_TOLERANCE = 0.25

    /**
     * Сколько килокалорий дают макросы по Этуотеру: 4 ккал на грамм белка
     * и углеводов, 9 — на грамм жира.
     *
     * Вынесена из [check], потому что считает по ней не только валидатор.
     * `LabelParser` расставляет по ней безымянные числа с этикетки, и обе стороны
     * обязаны считать одинаково: разойдясь, они дадут продукты, которые разбор
     * подставил, а валидатор здесь же и забраковал.
     */
    fun atwaterKcal(n: Nutriments): Double =
        // Макросы в сотых грамма, поэтому делим на сто: (сг * 4) / 100 = г * 4.
        (n.prot100 * 4 + n.fat100 * 9 + n.carb100 * 4) / 100.0

    fun check(n: Nutriments): NutrimentCheck {
        val error = firstError(n)
        if (error != null) return NutrimentCheck(error = error)
        return NutrimentCheck(warning = balanceWarning(n))
    }

    private fun firstError(n: Nutriments): String? = when {
        n.kcal100 < 0 || n.prot100 < 0 || n.fat100 < 0 || n.carb100 < 0 ->
            "Значения не могут быть отрицательными"

        n.kcal100 > KCAL_MAX ->
            "Больше $KCAL_MAX ккал на 100 г не бывает даже у чистого жира"

        n.prot100 > CENTIGRAMS_MAX || n.fat100 > CENTIGRAMS_MAX || n.carb100 > CENTIGRAMS_MAX ->
            "Белков, жиров или углеводов не может быть больше 100 г на 100 г"

        // Вода и зола тоже занимают место, так что сумма строго меньше ста;
        // но придираться к 99 г незачем — ловим только явную бессмыслицу.
        n.prot100 + n.fat100 + n.carb100 > CENTIGRAMS_MAX ->
            "Белки, жиры и углеводы вместе дают больше 100 г на 100 г"

        else -> null
    }

    /**
     * Сходятся ли калории с макросами по Этуотеру: 4 ккал на грамм белка
     * и углеводов, 9 — на грамм жира.
     *
     * Ловит самую частую опечатку ручного ввода — лишний или потерянный разряд.
     * Перепутанные местами жиры и углеводы она тоже обычно ловит.
     */
    private fun balanceWarning(n: Nutriments): String? {
        if (n.kcal100 <= BALANCE_MIN_KCAL) return null

        val fromMacros = atwaterKcal(n)
        if (abs(n.kcal100 - fromMacros) <= n.kcal100 * BALANCE_TOLERANCE) return null

        return "По белкам, жирам и углеводам выходит ${fromMacros.toInt()} ккал, " +
            "а указано ${n.kcal100}. Проверьте цифры на упаковке."
    }
}
