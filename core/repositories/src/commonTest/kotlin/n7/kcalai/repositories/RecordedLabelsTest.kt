    /**
     * На стакане «60 ккал / 250 кДж», а «ккал» прочитана как «кал», и подписи калорий
     * досталось число килоджоулей. БЖУ дают пятьдесят восемь — и выдают подмену.
     */
    @Test
    fun `килоджоули под видом калорий выдаёт сверка с БЖУ`() {
        val reading = LabelParser.parseLines(exponenta.toLines())

        assertEquals(60, reading.draft.kcal100)
        assertEquals(1_200, reading.draft.prot100)
        assertEquals(250, reading.draft.carb100)
    }

    /** Жиров на обезжиренном напитке и правда нет: без подписи ноль, потому что калории сходятся. */
    @Test
    fun `макрос без подписи — ноль когда калории сходятся и без него`() {
        val reading = LabelParser.parseLines(exponenta.toLines())

        assertEquals(0, reading.draft.fat100)
        assertEquals(listOf("Ж"), reading.trace.zeroedLabels)
    }

    /**
     * 842 кДж — это 201 ккал, а белки с жирами дают шесть. Значит, подпись углеводов
     * не на этикетке нет, а просто не влезла в кадр, и ноль здесь был бы выдумкой.
     */
    @Test
    fun `калории не сходятся — макрос без подписи не ноль а неизвестен`() {
        val reading = LabelParser.parseLines(balsamic.toLines())

        assertEquals(201, reading.draft.kcal100)
        assertEquals(50, reading.draft.prot100)
        assertEquals(null, reading.draft.carb100)
        assertEquals(emptyList(), reading.trace.zeroedLabels)
    }

    /** Строка разорвана: «580 | kДж/140 | ккал». За «кДж» стоят калории, и БЖУ это показывают. */
    @Test
    fun `калории за подписью килоджоулей выдаёт сверка с БЖУ`() {
        val reading = LabelParser.parseLines(curry.toLines())

        assertEquals(140, reading.draft.kcal100)
        assertEquals(3_100, reading.draft.carb100)
    }

    /** Строка таблицы, а не название: так продукт и уехал в дневник под именем «100 г продукта». */
    @Test
