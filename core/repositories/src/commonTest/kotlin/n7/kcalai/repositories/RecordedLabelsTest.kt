    @Test
    fun `кадры с прочитанным абзацем дают правду с пачки`() {
        val wrong = readable.mapNotNull { frame ->
            val reading = LabelParser.parseLines(frame.toLines())
            val got = with(reading.draft) { listOf(kcal100, prot100, fat100, carb100) }
            val ok = got == TRUTH && reading.confident &&
                reading.trace.route == LabelTrace.Route.LABELS
            if (ok) null else "${frame.session}: ${reading.trace.route.title} · ккал/Б/Ж/У $got"
        }

        if (wrong.isNotEmpty()) {
            fail("правда ккал/Б/Ж/У $TRUTH, а прочитано:\n" + wrong.joinToString("\n"))
        }
    }

    /**
     * Обрывки не голосуют и не закрывают съёмку.
     *
     * Голосует только разбор по подписям — см. LabelConsensus, — и обрывок,
     * выданный за прочитанную таблицу, отдавал бы голос за выдумку.
     */
    @Test
    fun `обрывки распознавания за таблицу не выдаются`() {
        for (frame in unreadable) {
            val reading = LabelParser.parseLines(frame.toLines())
            assertFalse(reading.confident, frame.session)
            assertFalse(reading.trace.tableFound, frame.session)
        }
    }

    /**
     * «EAC» — знак соответствия Таможенного союза, он стоит на каждой пачке
     * рядом с «Изделием кондитерским». Латинское слово из трёх букв с двумя
     * гласными проходит любую проверку на «похоже на слово», и с пастилы
     * в дневник уехало название «EAC».
     */
    @Test
    fun `знак EAC названием не становится`() {
        val lines = listOf(
            TextLine("EAC", centerX = 800f, centerY = 60f, width = 90f, height = 40f),
            TextLine("ИЗДЕЛИЕ КОНДИТЕРСКОЕ ПАСТИЛЬНОЕ.", centerX = 480f, centerY = 140f, width = 900f, height = 24f),
        )

        val names = LabelParser.nameCandidates(lines)

        assertEquals(listOf("Изделие кондитерское пастильное"), names)
    }

