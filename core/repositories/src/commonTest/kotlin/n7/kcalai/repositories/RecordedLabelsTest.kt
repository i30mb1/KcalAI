        val names = LabelParser.nameCandidates(exponenta.toLines())

        assertFalse(names.any { "100 г" in it }, "$names")
    }

    /** «RU» — метка языка перед абзацем для этой страны, а не часть имени. */
    @Test
    fun `метка языка в название не попадает`() {
        assertEquals("Соус карри", LabelParser.humanizeName("RU СОУС КАРРИ"))
    }

    /**
     * Рисованное «Соус» распознаётся латиницей как «Coye» и проходит за слово.
     * На русской пачке латиница — вензель или бренд, а название напечатано по-русски.
     */
    @Test
    fun `на русской пачке кириллица идёт раньше латиницы`() {
        val lines = listOf(
            TextLine("Coye", centerX = 700f, centerY = 500f, width = 300f, height = 90f),
            TextLine("СОУС «КАРРИ»", centerX = 400f, centerY = 800f, width = 400f, height = 30f),
        )

        assertEquals("Соус «карри»", LabelParser.nameCandidates(lines).first())
    }

    /**
     * Строки отчёта — в строки снимка.
     *
     * Отчёт разделяет строки « | », и в таком виде они и вставлены, чтобы
     * фикстуру можно было сверить с отчётом простым поиском.
     */
    private fun Frame.toLines(): List<TextLine> = lines.split(" | ").mapIndexed { index, text ->
        TextLine(
            text = text,
            centerX = 480f,
            centerY = 40f + index * LINE_PITCH,
            width = 900f,
            height = 20f,
        )
    }

    private companion object {
        val TRUTH = listOf(310, 250, 0, 7_600)
        const val LINE_PITCH = 30f
    }
