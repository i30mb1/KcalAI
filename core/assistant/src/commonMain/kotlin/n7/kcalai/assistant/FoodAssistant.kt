package n7.kcalai.assistant

import kotlinx.coroutines.flow.Flow
import n7.kcalai.resolver.ResolvedItem

/**
 * Нейросеть на телефоне: Gemini Nano через ML Kit.
 *
 * Она отвечает на те же два вопроса, что и резолвер, — «что это» и «сколько грамм», —
 * только там, где правила не справились. Цифры КБЖУ она не называет никогда:
 * продукт выбирается из локальной базы через инструмент поиска, и всё, что
 * она предлагает, человек подтверждает тапом.
 *
 * Есть не на всех телефонах. Экран спрашивает [ready] один раз и без модели
 * работает так же, как работал до неё.
 */
interface FoodAssistant {

    /** Модель на этом телефоне есть и скачана. */
    suspend fun ready(): Boolean

    /**
     * Фраза, которую не разобрал поиск, -> блюда с граммами.
     *
     * «тарелка борща и два куска хлеба» -> два предложения. Пустой список — модель
     * тоже не поняла, о чём речь.
     */
    suspend fun propose(text: String): List<ResolvedItem>

    /**
     * Вопрос про дневник -> ответ, по мере того как модель его пишет.
     *
     * Каждое значение — весь ответ на этот момент, а не очередной кусок: экран
     * просто показывает последнее.
     */
    fun answer(question: String): Flow<String>
}
