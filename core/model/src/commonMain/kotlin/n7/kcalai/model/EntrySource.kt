package n7.kcalai.model

/** Чем именно была добавлена запись — нужно для диагностики качества распознавания. */
enum class EntrySource {
    BARCODE,
    TEXT,
    MANUAL,
    LLM,
    VISION,

    /**
     * Подсказал телефон рядом, а человек подтвердил тапом.
     *
     * Отдельно от [MANUAL]: граммы и числа пришли с чужого телефона, своими руками
     * человек их не набирал. Ранжированию такая запись не урок — как и предложенная
     * нейросетью: выбирал не он.
     */
    SHARED,
}
