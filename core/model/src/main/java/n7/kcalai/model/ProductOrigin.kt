package n7.kcalai.model

/**
 * Откуда взялись цифры сетевого ответа.
 *
 * Это не диагностика, а юридическая граница. Open Food Facts лежит под ODbL —
 * лицензией с share-alike на производную базу: если данные оттуда попадут в общий
 * пул и будут из него раздаваться, публиковать придётся весь пул целиком, включая
 * вклад наших пользователей. Живой запрос ради показа одному человеку производной
 * базы не создаёт, обязательства возникают только при распространении.
 *
 * Поэтому помеченное [OFF] живёт исключительно в `cached_product` и никогда
 * не попадает в очередь отправки. В `contribution` уходит только то, что человек
 * ввёл руками, — а оно не производное ни от чего.
 */
enum class ProductOrigin {
    /** Свой сервер: наш собственный пул, раздавать можно. */
    SERVER,

    /** Open Food Facts: показать можно, отправить дальше — нельзя. */
    OFF,
}
