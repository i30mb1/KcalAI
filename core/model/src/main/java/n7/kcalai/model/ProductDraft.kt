package n7.kcalai.model

/**
 * Частично известный продукт — то, чем заполняется форма «новый продукт».
 *
 * Все поля отдельные и все могут отсутствовать, и это не небрежность. Заполнять
 * форму будет не только человек: в v2 сюда придёт распознавание таблицы «Пищевая
 * ценность на 100 г» с упаковки, а OCR штатно читает три числа из четырёх —
 * блик на плёнке съедает строку. Требовать от источника полный комплект значило бы
 * выбрасывать три полезных числа из-за одного нечитаемого.
 *
 * Человек в любом случае видит форму и подтверждает цифры сам: подставленное
 * значение — это сэкономленный ввод, а не принятое за него решение.
 */
data class ProductDraft(
    val name: String? = null,
    /** Целые килокалории на 100 г. */
    val kcal100: Int? = null,
    /** Белки, сотые грамма на 100 г. */
    val prot100: Int? = null,
    /** Жиры, сотые грамма на 100 г. */
    val fat100: Int? = null,
    /** Углеводы, сотые грамма на 100 г. */
    val carb100: Int? = null,
    val servingG: Int? = null,
) {
    companion object {
        /** Пустой черновик: сегодня форма всегда открывается с ним. */
        val EMPTY: ProductDraft = ProductDraft()
    }
}
