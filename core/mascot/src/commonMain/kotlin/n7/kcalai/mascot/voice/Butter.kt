            +"{food} — в дневнике. Тепло и уютно."
            +"Готово: {food}. Наслаждайся."
            +"Есть: {food}. Мурр."
            +"Уже в дневнике: {food}. Приятного аппетита."
            +"Записано: {food}. Ешь не спеша."
        }
    }

    topic(Topic.POKE) {
        say {
            +"Хи-хи, щекотно!"
            +"Ой, я же растаю!"
            +"Мягко, мягко!"
            +"Проверяешь, свежее ли?"
            +"Мурр… то есть ай!"
            +"Я масло, а не кнопка!"
