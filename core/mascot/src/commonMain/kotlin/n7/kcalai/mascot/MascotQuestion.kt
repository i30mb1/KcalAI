package n7.kcalai.mascot

import n7.kcalai.database.MascotMessageEntity
import n7.kcalai.model.Mascot

/**
 * О чём персонажи спрашивают — и кто.
 *
 * Вопрос — сообщение в ленте, как любое другое: задан — лежит в переписке своего
 * дня, отвечен — остаётся там же, с выбранным ответом и погасшими кнопками. Лента —
 * переписка, и отвеченное из неё не пропадает.
 */
enum class MascotQuestion(val mascot: Mascot, val text: String) {
    /** Как зовут: на первую запись дня, когда человек уже начал. */
    NAME(Mascot.EGG, "Кстати, как тебя зовут? Буду знать, к кому обращаться."),

    /** Можно ли писать первыми: после имени, со второй записи дня. */
    WRITE(
        Mascot.GRAIN,
        "Можно мы будем иногда писать тебе сами? Если пропадёшь или забудешь поесть. " +
            "Не чаще пары раз в день — честно.",
    ),

    /** Подключить беговую дорожку к телефону: один раз, тем, кто открывает дневник с компьютера. */
    TREADMILL(
        Mascot.GRAIN,
        "Ходишь по беговой дорожке? Подключу её к телефону — прогулки и шаги будут записываться сами.",
    ),

    /** Читать шагомер телефона: его шаги складываются с дорожкой, цель шагов одна на всё. */
    STEPS(
        Mascot.GRAIN,
        "Считать и шаги телефона? Сложу их с дорожкой — цель шагов одна на всё.",
    ),
    ;

    /** Тема сообщения в базе. Не тема голосов: вопрос всякий раз звучит одними словами. */
    val topic: String get() = "ASK_$name"
}

/** Вопрос, если сообщение — вопрос. */
val MascotMessageEntity.question: MascotQuestion?
    get() = MascotQuestion.entries.firstOrNull { it.topic == topic }

/**
 * Вопрос держит слово: задан после последней записи и ждёт ответа.
 *
 * Пока так, остальные молчат — подсказки в ленте и новости о фоновой работе:
 * персонажи говорят по одному, и вопрос не тонет среди других реплик. Человек
 * записал что-то, не ответив, — вопрос остаётся в переписке с живыми кнопками,
 * но слово уже не держит: ждать ответа вечно незачем.
 *
 * @param lastEntryAt когда сделана последняя запись; `null` — записей нет
 */
fun awaitsAnswer(said: List<MascotMessageEntity>, lastEntryAt: Long?): Boolean =
    said.any { it.question != null && it.choice == null && it.createdAt >= (lastEntryAt ?: Long.MIN_VALUE) }
