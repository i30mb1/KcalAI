package n7.kcalai.nearby

import kotlinx.coroutines.flow.Flow

/**
 * Телефон рядом, которому можно предложить запись.
 *
 * @param name как назвался владелец. Подпись, а не удостоверение: имя объявлено
 *        его телефоном и ничем не подтверждено.
 */
data class Peer(val name: String, val host: String, val port: Int)

/**
 * Кто рядом — и как рассказать о себе.
 *
 * mDNS/DNS-SD: на Android это `NsdManager`, на iOS Bonjour, и это один протокол —
 * они встречаются на проводе без всяких мостов. Так же находят друг друга принтеры
 * и колонки, и ровно поэтому путь выбран этот: Wi-Fi Direct с iOS не соединяется
 * в принципе — у Apple свой AWDL, и сканеры сторон не видят объявлений друг друга.
 *
 * Общая сеть обязательна. Гостевой Wi-Fi с изоляцией клиентов, разные сети
 * и мобильный интернет фичу выключают — обойти это нечем, и человеку об этом
 * говорит персонаж, а не вечный спиннер.
 *
 * Платформенной реализацией, а не `expect`/`actual`: так же устроена база —
 * `buildKcalDatabase` своя у каждой платформы, а приложение берёт нужную.
 */
interface NearbyDiscovery {

    /**
     * Рассказать о себе соседям: имя владельца и порт приёмника.
     *
     * Объявление видно всем в сети — поэтому его включают, только пока фича
     * нужна, и об этом сказано в политике.
     */
    suspend fun advertise(name: String, port: Int)

    /**
     * Кто рядом. Поиск идёт, пока на поток подписаны: в кармане искать некого.
     *
     * Пустой список — не ошибка, а обычное начало: соседи появляются не сразу.
     */
    fun peers(): Flow<List<Peer>>

    /** Перестать объявлять себя и искать. */
    fun stop()
}

/**
 * Тип службы в сети. Подчёркивание и `_tcp` — требование DNS-SD, а не украшение;
 * то же имя обязано стоять в `NSBonjourServices` в Info.plist, иначе iOS
 * не даст ни искать, ни объявлять.
 */
const val OFFER_SERVICE_TYPE = "_kcalai._tcp"
